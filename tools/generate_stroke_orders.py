"""Generate simplified five-stroke prefixes from the pinned cnchar inputs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/cnchar"
DEST = ROOT / "app/src/main/assets/stroke/orders.tsv"


def generate():
    orders = json.loads((SOURCE / "stroke-order-jian.json").read_text())
    table = json.loads((SOURCE / "stroke-table.json").read_text())
    variants = json.loads((SOURCE / "trad-simple.json").read_text())
    traditional_only = set(variants["trad"]) - set(variants["simple"])
    # Five-stroke convention: rising strokes are horizontal; vertical hooks
    # remain vertical, not folded strokes. Other bends/hooks belong to fold.
    categories = {letter: "5" for letter in table}
    categories.update(dict.fromkeys("ji", "1"))
    categories.update(dict.fromkeys("fg", "2"))
    categories.update(dict.fromkeys("s", "3"))
    categories.update(dict.fromkeys("kld", "4"))
    if any(len(char) != 1 or not code or set(code) - table.keys() for char, code in orders.items()):
        raise ValueError("Invalid upstream stroke entry")
    rows = [f"{char}\t{''.join(categories[c] for c in code)}\n"
            for char, code in sorted(orders.items()) if char not in traditional_only]
    return "# Generated by tools/generate_stroke_orders.py; cnchar MIT; see third_party/cnchar.\n" + "".join(rows)


if __name__ == "__main__":
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text(generate(), encoding="utf-8")
